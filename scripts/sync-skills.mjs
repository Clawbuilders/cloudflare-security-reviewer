#!/usr/bin/env node
/**
 * Extract what the reviewer needs from vendored skill files into TypeScript modules, so Workers and tests can import
 * them without bundler rules. Run after updating the vendored files:
 *   npm run skills:sync
 *
 *   starter/skills/security-audit  (cloudflare/security-audit-skill, MIT)  -> starter/src/lib/skills.generated.ts
 *   skills/codeguard                (CoSAI Project CodeGuard, CC-BY-4.0)    -> src/codeguard.generated.ts (Advanced only)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SKILL_COMMIT = "c1c8a8c1471069fb0e188eeaff69b8e8db6564a8";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "starter/skills/security-audit");
const out = join(root, "starter/src/lib/skills.generated.ts");

const DOMAIN_FILES = ["AI-AND-LLM", "CLIENT-SIDE", "CLOUD-AND-DEPLOYMENT", "DATA-ISOLATION-AND-LIFECYCLE", "SUPPLY-CHAIN-AND-RELEASE", "WEB-PROTOCOL-AND-AUTH"];

const tidyTitle = (t) => t.replace(/\s*\(subagent_type: `\w+`\)/g, "").replace(/\s*\((include in every|apply before|apply across)[^)]*\)/g, "").trim();
const unfence = (t) => t.replace(/^```\w*\s*$/gm, "").trim();

function domainFile(stem) {
  const text = readFileSync(join(dir, `${stem}.md`), "utf8");
  const parts = text.split(/^## /m).slice(1);
  const d = { file: `${stem}.md`, core: "", classes: [], validation: "" };
  for (const p of parts) {
    const nl = p.indexOf("\n");
    const title = p.slice(0, nl);
    const body = unfence(p.slice(nl + 1));
    if (/^Core discipline/.test(title)) d.core = body;
    else if (/^Validation rules/.test(title)) d.validation = body;
    else d.classes.push({ title: tidyTitle(title), text: body });
  }
  if (!d.core || !d.validation || d.classes.length === 0) throw new Error(`${stem}.md: unexpected structure`);
  return d;
}

function attackClasses() {
  const text = readFileSync(join(dir, "ATTACK-CLASSES.md"), "utf8");
  const important = text.match(/\*\*Important\*\*:([^\n]+)/);
  const groups = text.split(/^\*\*(.+?)\*\* \(subagent_type: `\w+`\)\s*$/m);
  // groups: [preamble, title1, body1, title2, body2, ...]
  const classes = [];
  for (let i = 1; i < groups.length; i += 2) {
    let body = groups[i + 1].replace(/\*\*Important\*\*:[^\n]+/, "").trim();
    classes.push({ title: groups[i].trim(), text: body });
  }
  if (classes.length < 5 || !important) throw new Error("ATTACK-CLASSES.md: unexpected structure");
  return { file: "ATTACK-CLASSES.md", core: "", classes, validation: important[1].trim() };
}

function verifierChecklist() {
  const text = readFileSync(join(dir, "VALIDATION-AND-REPORTING.md"), "utf8");
  const m = text.match(/You did not write this candidate\.[\s\S]*?(?=\nReturn exactly one JSON object)/);
  if (!m) throw new Error("VALIDATION-AND-REPORTING.md: candidate-verifier prompt not found");
  // Keep the source-only steps: verify the trace (1), reconstruct the controls on the path (2), match impact and
  // confidence to the evidence (4). Steps about sandboxed execution and artifacts do not apply to a source-only reviewer.
  const steps = m[0].split(/\n(?=\d\. )/).filter((s) => /^(1|2|4)\. /.test(s)).map((s) => s.replace(/\s*\n\s+/g, " ").trim());
  if (steps.length !== 3) throw new Error("VALIDATION-AND-REPORTING.md: verifier steps changed");
  return steps.join("\n");
}

const domains = { "ATTACK-CLASSES": attackClasses() };
for (const stem of DOMAIN_FILES) domains[stem] = domainFile(stem);

const body = `/**
 * GENERATED by scripts/sync-skills.mjs from starter/skills/security-audit (cloudflare/security-audit-skill, MIT,
 * Copyright (c) 2025-2026 Cloudflare, Inc.). Do not edit by hand; run \`npm run skills:sync\`.
 */

export const SKILL_COMMIT = ${JSON.stringify(SKILL_COMMIT)};
export const SKILL_SOURCE = "https://github.com/cloudflare/security-audit-skill";

export interface SkillClass {
  title: string;
  text: string;
}

export interface SkillDomain {
  file: string;
  /** "Core discipline": included in every prompt for this domain. */
  core: string;
  /** Attack-class sections, in the skill's order. */
  classes: SkillClass[];
  /** "Validation rules": applied before reporting any finding in this domain. */
  validation: string;
}

export const DOMAINS: Record<string, SkillDomain> = ${JSON.stringify(domains, null, 2)};

/** Source-only steps of the skill's candidate-verifier prompt. */
export const VERIFIER_CHECKLIST = ${JSON.stringify(verifierChecklist())};
`;
// ---------- CoSAI Project CodeGuard (used by the Advanced track's /security fix) ----------

const CODEGUARD_COMMIT = "41160d54980bab0618165485ade3cfd2ade93288";
const cgDir = join(root, "skills/codeguard/rules");
const cgOut = join(root, "src/codeguard.generated.ts");
const rules = {};
for (const name of readdirSync(cgDir).filter((n) => n.endsWith(".md")).sort()) {
  const text = readFileSync(join(cgDir, name), "utf8");
  const fm = text.match(/^---\n([\s\S]*?)\n---\n/);
  const description = fm?.[1].match(/^description:\s*(.+)$/m)?.[1].trim();
  const id = text.match(/^rule_id:\s*(\S+)/m)?.[1];
  if (!fm || !description || !id) throw new Error(`${name}: unexpected CodeGuard rule structure`);
  const bodyText = text.slice(fm[0].length).replace(/^rule_id:.*\n/m, "").replace(/\n{3,}/g, "\n\n").trim();
  rules[id.replace(/^codeguard-\d-/, "")] = { file: name, title: description, text: bodyText };
}
const cgBody = `/**
 * GENERATED by scripts/sync-skills.mjs from skills/codeguard (CoSAI Project CodeGuard,
 * https://github.com/cosai-oasis/project-codeguard, CC-BY-4.0). Do not edit by hand; run \`npm run skills:sync\`.
 */

export const CODEGUARD_COMMIT = ${JSON.stringify(CODEGUARD_COMMIT)};
export const CODEGUARD_SOURCE = "https://github.com/cosai-oasis/project-codeguard";

export interface CodeGuardRule {
  file: string;
  title: string;
  text: string;
}

export const CODEGUARD_RULES: Record<string, CodeGuardRule> = ${JSON.stringify(rules, null, 2)};
`;

const outputs = [
  [out, body, `${Object.keys(domains).length} domains`],
  [cgOut, cgBody, `${Object.keys(rules).length} CodeGuard rules`],
];
if (process.argv.includes("--check")) {
  let stale = false;
  for (const [file, text] of outputs) {
    if (readFileSync(file, "utf8") !== text) {
      console.error(`${file} is out of date: run npm run skills:sync`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log("generated skill modules are up to date");
} else {
  for (const [file, text, what] of outputs) {
    writeFileSync(file, text);
    console.log(`wrote ${file}: ${what}, ${text.length} bytes`);
  }
}
